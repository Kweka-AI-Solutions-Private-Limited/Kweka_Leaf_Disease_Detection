@router.post("/exchange", response_model=AuthResponse)
def exchange_code_for_token(
    payload: ExchangeCodeRequest,
    db: Database = Depends(get_db)
):
    """
    Exchanges parent platform ?exchange_code=<token> for a signed JWT access token.
    1. Looks up token in `kp_user_tokens` collection (type: 'EXCHANGE').
    2. Verifies token is unused and not expired.
    3. Marks token as used (`is_used = True`).
    4. Retrieves user record from `kp_users`.
    5. Signs and returns a 7-day HS256 JWT access token.
    """
    code = payload.exchange_code.strip()
    if not code:
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail="Exchange code must not be empty."
        )

    # 1. Look up exchange token in kp_user_tokens
    token_doc = db["kp_user_tokens"].find_one({
        "token": code,
        "token_type": "EXCHANGE"
    })

    if not token_doc:
        raise HTTPException(
            status_code=status.HTTP_401_UNAUTHORIZED,
            detail="Invalid or unrecognized exchange code."
        )

    now = datetime.now(timezone.utc)

    # 2. Check if already used
    if token_doc.get("is_used", False):
        raise HTTPException(
            status_code=status.HTTP_401_UNAUTHORIZED,
            detail="This exchange code has already been used. Please launch again from the Kweka platform."
        )

    # 3. Check expiration (allowing 10-minute grace window for clock skew)
    expires_at = token_doc.get("expires_at")
    if expires_at:
        # Normalize timezone if needed
        if expires_at.tzinfo is None:
            expires_at = expires_at.replace(tzinfo=timezone.utc)
        if now > (expires_at + timedelta(minutes=10)):
            raise HTTPException(
                status_code=status.HTTP_401_UNAUTHORIZED,
                detail="Exchange code has expired. Please launch again from the Kweka platform."
            )

    # 4. Mark token as consumed
    try:
        db["kp_user_tokens"].update_one(
            {"_id": token_doc["_id"]},
            {"$set": {"is_used": True, "updatedAt": now}}
        )
    except Exception as e:
        print(f"[WARN] Failed to mark exchange token as used: {e}")

    # 5. Fetch User Profile from kp_users
    user_id_raw = token_doc.get("user_id")
    if isinstance(user_id_raw, str):
        try:
            user_id_raw = ObjectId(user_id_raw)
        except Exception:
            pass

    user_doc = db["kp_users"].find_one({"_id": user_id_raw})
    if not user_doc:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail="User account associated with exchange code was not found."
        )

    if not user_doc.get("is_active", True):
        raise HTTPException(
            status_code=status.HTTP_403_FORBIDDEN,
            detail="User account is deactivated."
        )

    user_id_str = str(user_doc["_id"])
    first_name = user_doc.get("first_name", "")
    last_name = user_doc.get("last_name", "")
    full_name = f"{first_name} {last_name}".strip() or user_doc.get("email", "Agronomist User")
    email = user_doc.get("email")
    company = user_doc.get("company", "Kweka AI Solutions")
    job_title = user_doc.get("job_title", "Agronomist")
    role = user_doc.get("role", "USER")

    # 6. Issue signed JWT token (7 days duration)
    issued_at = int(now.timestamp())
    expires_at_timestamp = int((now + timedelta(days=7)).timestamp())

    jwt_payload = {
        "sub": user_id_str,
        "user_id": user_id_str,
        "email": email,
        "name": full_name,
        "first_name": first_name,
        "last_name": last_name,
        "company": company,
        "job_title": job_title,
        "role": role,
        "iat": issued_at,
        "exp": expires_at_timestamp,
    }

    jwt_token = jwt.encode(jwt_payload, JWT_SECRET_KEY, algorithm=JWT_ALGORITHM)

    # 7. Log Activity
    log_activity(
        db=db,
        action="USER_EXCHANGE_AUTH",
        category="AUTH",
        description=f"Authenticated {full_name} ({email}) via parent platform exchange code.",
        status="SUCCESS",
        user_id=user_id_str,
        metadata={
            "user_id": user_id_str,
            "email": email,
            "company": company,
            "prototype_id": str(token_doc.get("prototype_id", ""))
        }
    )

    user_profile = UserProfileResponse(
        id=user_id_str,
        email=email,
        name=full_name,
        first_name=first_name,
        last_name=last_name,
        company=company,
        job_title=job_title,
        mobile_number=user_doc.get("mobile_number"),
        role=role,
        is_active=user_doc.get("is_active", True)
    )

    return AuthResponse(
        token=jwt_token,
        token_type="Bearer",
        expires_in_days=7,
        user=user_profile
    )


@router.get("/me", response_model=UserProfileResponse)
def get_current_user_profile(
    authorization: Optional[str] = Header(None, alias="Authorization"),
    db: Database = Depends(get_db)
):
    """
    Verifies and returns user profile decoded from the Authorization: Bearer <jwt> header.
    """
    if not authorization or not authorization.startswith("Bearer "):
        raise HTTPException(
            status_code=status.HTTP_401_UNAUTHORIZED,
            detail="Missing or malformed Authorization header."
        )

    token = authorization.split("Bearer ", 1)[1].strip()
    payload = decode_jwt_token(token)
    if not payload:
        raise HTTPException(
            status_code=status.HTTP_401_UNAUTHORIZED,
            detail="JWT token signature is invalid or token has expired."
        )

    user_id_str = payload.get("user_id") or payload.get("sub")
    if not user_id_str:
        raise HTTPException(
            status_code=status.HTTP_401_UNAUTHORIZED,
            detail="JWT token does not contain a valid user identity."
        )

    # Fetch live record if available
    try:
        user_doc = db["kp_users"].find_one({"_id": ObjectId(user_id_str)})
        if user_doc:
            first_name = user_doc.get("first_name", "")
            last_name = user_doc.get("last_name", "")
            return UserProfileResponse(
                id=user_id_str,
                email=user_doc.get("email"),
                name=f"{first_name} {last_name}".strip() or user_doc.get("email", "User"),
                first_name=first_name,
                last_name=last_name,
                company=user_doc.get("company"),
                job_title=user_doc.get("job_title"),
                mobile_number=user_doc.get("mobile_number"),
                role=user_doc.get("role", "USER"),
                is_active=user_doc.get("is_active", True)
            )
    except Exception:
        pass

    # Fallback to payload claims
    return UserProfileResponse(
        id=user_id_str,
        email=payload.get("email"),
        name=payload.get("name", "User"),
        first_name=payload.get("first_name"),
        last_name=payload.get("last_name"),
        company=payload.get("company"),
        job_title=payload.get("job_title"),
        role=payload.get("role", "USER"),
        is_active=True
    )
