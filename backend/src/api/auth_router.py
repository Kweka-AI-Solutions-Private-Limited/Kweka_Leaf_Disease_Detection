from datetime import datetime, timezone, timedelta
from typing import Optional, Dict, Any
from bson import ObjectId
from pydantic import BaseModel, Field
from fastapi import APIRouter, Depends, HTTPException, status, Header
from pymongo.database import Database

from db.connection import get_db
from db.activity_logger import log_activity

router = APIRouter(prefix="/auth", tags=["Authentication & Platform Exchange"])

JWT_SECRET_KEY = os.getenv("JWT_SECRET_KEY", "MetSiq2G3wpDGnrtS5w6rBf17KnFZJRr")
JWT_ALGORITHM = "HS256"


# ── Pydantic Request & Response Models ──────────────────────────────────────────

class ExchangeCodeRequest(BaseModel):
    exchange_code: str = Field(..., description="Single-use exchange token generated by Kweka parent platform")


class UserProfileResponse(BaseModel):
    id: str
    email: Optional[str] = None
    name: str
    first_name: Optional[str] = None
    last_name: Optional[str] = None
    company: Optional[str] = None
    job_title: Optional[str] = None
    mobile_number: Optional[str] = None
    role: str = "USER"
    is_active: bool = True


class AuthResponse(BaseModel):
    token: str
    token_type: str = "Bearer"
    expires_in_days: int = 7
    user: UserProfileResponse


# ── Helper Functions ──────────────────────────────────────────────────────────

def decode_jwt_token(token: str) -> Optional[Dict[str, Any]]:
    """Decodes and validates a Bearer JWT token signature and expiration."""
    try:
        payload = jwt.decode(token, JWT_SECRET_KEY, algorithms=[JWT_ALGORITHM])
        return payload
    except (jwt.ExpiredSignatureError, jwt.InvalidTokenError):
        return None


def get_current_user_id(
    authorization: Optional[str] = Header(None, alias="Authorization"),
    x_user_id: Optional[str] = Header(None, alias="X-User-ID")
) -> str:
    """
    Extracts isolated user_id context:
      1. From validated JWT Bearer token in the 'Authorization' header.
      2. Falls back to 'X-User-ID' header for backward compatibility.
      3. Defaults to 'default_user' if unprovided.
    """
    if authorization and authorization.startswith("Bearer "):
        token = authorization.split("Bearer ", 1)[1].strip()
        payload = decode_jwt_token(token)
        if payload and payload.get("user_id"):
            return str(payload["user_id"])

    if x_user_id and x_user_id.strip():
        return x_user_id.strip()

    return "default_user"


