"""
auth_router.py — Parent Platform Exchange Code & JWT Authentication Router
-----------------------------------------------------------------------------
Orchestrates:
  1. Parent platform exchange code verification against `kp_user_tokens`
  2. User identity retrieval from `kp_users`
  3. HS256 JWT Token issuance using `JWT_SECRET_KEY`
  4. Bearer JWT validation & User Context extraction for downstream endpoints
"""

